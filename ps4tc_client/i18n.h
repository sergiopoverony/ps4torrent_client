#pragma once
#include <string>
#include <stdint.h>

// Тексты интерфейса. Встроенный английский всегда есть как запасной вариант.
// Если язык системы русский, клиент забирает /lang/ru.json у ps4torrentd, иначе /lang/en.json.
// Если файла нет или он битый, остаётся встроенный английский.

// Читает язык системы PS4. Вызвать один раз при старте.
void i18n_init();

// Подгружает языковой файл с демона, когда тот ответил. Безопасно вызывать часто:
// сам ограничивает частоту попыток и после успеха ничего не делает.
void i18n_tick(bool serverOk, uint64_t nowUs);

// Текст по ключу; если в языковом файле ключа нет, возвращает def.
std::string tr(const char* key, const char* def);
